#!/usr/bin/env python3
"""Generate the fixed semicolon-only entity table from a local WHATWG JSON file.

Download https://html.spec.whatwg.org/entities.json separately, then run:
python3 scripts/generate_entities.py /path/to/entities.json > crates/mdstream-core/src/entity_names.rs
No downloads are performed during builds or tests.
"""

import hashlib
import json
import pathlib
import sys

raw = pathlib.Path(sys.argv[1]).read_bytes()
entries = sorted(
    (name[1:-1], entry["characters"])
    for name, entry in json.loads(raw).items()
    if name.endswith(";")
)
assert len(entries) == 2125
assert max(len(name) for name, _ in entries) == 31
assert all(len(value.encode()) <= 8 for _, value in entries)
print("// Generated by scripts/generate_entities.py; do not edit by hand.")
print("// Source: https://html.spec.whatwg.org/entities.json (WHATWG HTML named references)")
print(f"// Input SHA-256: {hashlib.sha256(raw).hexdigest()}")
print("pub(super) static NAMES: &[(&str, &str)] = &[")
for name, value in entries:
    escaped = "".join("\\u{" + format(ord(c), "x") + "}" for c in value)
    print(f'    ("{name}", "{escaped}"),')
print("];")
