#!/usr/bin/env python3
"""Generate Unicode 17.0.0 default full case folding from checked-in local data.

Run with --check for an offline byte-for-byte verification. There is no network,
Python Unicode database, build hook, or runtime dependency involved.
"""

import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data/unicode/17.0.0/CaseFolding.txt"
LICENSE = ROOT / "data/unicode/LICENSE.txt"
OUTPUT = ROOT / "crates/mdstream-core/src/case_folding.rs"
DATA_SHA256 = "ff8d8fefbf123574205085d6714c36149eb946d717a0c585c27f0f4ef58c4183"
LICENSE_SHA256 = "e7a93b009565cfce55919a381437ac4db883e9da2126fa28b91d12732bc53d96"


def scalar(code):
    value = int(code, 16)
    if value > 0x10FFFF or 0xD800 <= value <= 0xDFFF:
        raise ValueError("non-scalar in pinned data")
    return chr(value)


def generate(source):
    raw = source.read_bytes()
    if hashlib.sha256(raw).hexdigest() != DATA_SHA256:
        raise ValueError("input is not the pinned Unicode 17.0.0 CaseFolding.txt")
    if hashlib.sha256(LICENSE.read_bytes()).hexdigest() != LICENSE_SHA256:
        raise ValueError("Unicode License V3 differs from the pinned copy")
    entries = {}
    for line in raw.decode("utf-8").splitlines():
        body = line.split("#", 1)[0].strip()
        if not body:
            continue
        code, status, mapping, empty = map(str.strip, body.split(";"))
        if empty or status not in ("C", "F", "S", "T"):
            raise ValueError("unexpected CaseFolding record")
        key = scalar(code)
        value = "".join(scalar(c) for c in mapping.split())
        # Default full folding is exactly C + F; S and Turkic T are excluded.
        if status in ("C", "F"):
            if key in entries or not value:
                raise ValueError("duplicate or empty full folding")
            entries[key] = value
    assert len(entries) == 1585
    assert max(map(len, entries.values())) == 3
    assert max(len(s.encode("utf-8")) for s in entries.values()) == 6
    assert max(
        len(s.encode("utf-8")) / len(c.encode("utf-8"))
        for c, s in entries.items()
    ) == 3
    # Outputs are already folded. Missing scalars are identity mappings.
    assert all(
        "".join(entries.get(c, c) for c in value) == value
        for value in entries.values()
    )
    lines = [
        "// Generated by scripts/generate_case_folding.py; do not edit by hand.",
        "// Unicode 17.0.0 default full folding: C + F, excluding S and Turkic T.",
        "// Source: https://www.unicode.org/Public/17.0.0/ucd/CaseFolding.txt",
        f"// Input SHA-256: {DATA_SHA256}",
        "// Unicode License V3: data/unicode/LICENSE.txt (copyright/permission notice).",
        "// 1585 sorted mappings; absent scalars map to themselves.",
        "// At most 3 output scalars / 6 UTF-8 bytes per mapped scalar; byte ratio <= 3.",
        "pub(super) static MAPPINGS: &[(char, &str)] = &[",
    ]
    for key, value in sorted(entries.items()):
        escaped = "".join(f"\\u{{{ord(c):x}}}" for c in value)
        lines.append(f"    ('\\u{{{ord(key):x}}}', \"{escaped}\"),")
    lines.append("];")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", nargs="?", type=Path, default=SOURCE)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate(args.source)
    if args.check:
        if OUTPUT.read_bytes() != generated.encode("utf-8"):
            parser.error("checked-in case folding table differs from pinned Unicode data")
        print("Unicode 17.0.0: data/license hashes, 1585 C+F mappings and expansion bounds verified")
    else:
        print(generated, end="")


if __name__ == "__main__":
    main()
