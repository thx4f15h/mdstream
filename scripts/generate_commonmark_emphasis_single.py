#!/usr/bin/env python3
"""Extract Emphasis single-delimiter examples 350–373 from the pinned local spec.

This subset has 24 examples; Emphasis 374–481 remain outside this score.

Download https://spec.commonmark.org/0.31.2/spec.json separately, then run:
python3 scripts/generate_commonmark_emphasis_single.py /path/to/spec.json > crates/mdstream-core/tests/fixtures/commonmark_emphasis_single.rs
Use --check to verify the checked-in fixture without writing it. No network or
mdstream parser is used here; upstream Markdown and HTML are copied unchanged.
"""

import argparse
import hashlib
import json
from pathlib import Path


def generate(path):
    raw = path.read_bytes()
    digest = "d431b29d97b6f73e69d547109cf5081578fac931e72afe95639ebe766c1b2a20"
    if hashlib.sha256(raw).hexdigest() != digest:
        raise ValueError("input is not the pinned CommonMark 0.31.2 spec.json")
    cases = [
        case for case in json.loads(raw)
        if case["section"] == "Emphasis and strong emphasis" and 350 <= case["example"] <= 373
    ]
    if [case["example"] for case in cases] != list(range(350, 374)):
        raise ValueError("Emphasis single-delimiter subset section membership changed")
    lines = [
        "// Generated by scripts/generate_commonmark_emphasis_single.py; do not edit by hand.",
        "// CommonMark 0.31.2, Emphasis and strong emphasis subset 350–373 only, John MacFarlane.",
        "// Source: https://spec.commonmark.org/0.31.2/spec.json",
        "// License: CC BY-SA 4.0 https://creativecommons.org/licenses/by-sa/4.0/",
        f"// Input SHA-256: {digest}",
        "// Markdown and expected HTML are copied verbatim, including whitespace.",
        "const EMPHASIS_CASES: &[(usize, &str, &str)] = &[",
    ]
    for case in cases:
        lines.append(f'    // spec.txt lines {case["start_line"]}–{case["end_line"]}.')
        lines.append(f'    ({case["example"]},')
        for field in ["markdown", "html"]:
            # Use literal Unicode and Rust-compatible JSON control escapes.
            # Escaping whitespace avoids invisible trailing spaces in the file
            # while preserving every upstream character in the compiled value.
            lines.append(f'        {json.dumps(case[field], ensure_ascii=False)},')
        lines.append("    ),")
    lines.append("];")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("spec", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate(args.spec)
    if args.check:
        fixture = Path(__file__).resolve().parents[1] / "crates/mdstream-core/tests/fixtures/commonmark_emphasis_single.rs"
        if fixture.read_text() != generated:
            parser.error("checked-in Emphasis single-delimiter subset fixture differs from the pinned upstream data")
        print("CommonMark 0.31.2 Emphasis single-delimiter subset fixture: 24 verbatim examples verified")
    else:
        print(generated, end="")


if __name__ == "__main__":
    main()
