#!/usr/bin/env python3
"""Extract the complete Autolinks (extension) section from the pinned official GFM HTML.

Download https://github.github.com/gfm/ separately, then run:
python3 scripts/generate_gfm_autolinks_extension.py /path/to/gfm.html > crates/mdstream-core/tests/fixtures/gfm_autolinks_extension.rs
Use --check to verify the checked-in fixture without writing it. No network or
mdstream parser is used here. Only HTML presentation markup is decoded; Markdown
and expected HTML code-block contents retain every upstream character.
"""

import argparse
import hashlib
from html.parser import HTMLParser
import json
from pathlib import Path


class AutolinksExtension(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.active = False
        self.cases = []
        self.field = None

    def handle_starttag(self, tag, attributes):
        attrs = dict(attributes)
        if self.field is not None:
            # The pinned section marks each space with a span. Preserve its
            # text, and reject unknown presentation markup (e.g. tab arrows).
            if tag != "span" or attrs != {"class": "space"}:
                raise ValueError("unexpected markup inside an example")
            return
        if tag in ("h1", "h2"):
            self.active = attrs.get("id") == "autolinks-extension-"
        if not self.active:
            return
        if tag == "div" and attrs.get("class") == "example":
            self.cases.append({
                "number": int(attrs["id"].removeprefix("example-")),
                "line": self.getpos()[0],
            })
        if tag == "code" and attrs.get("class") in ("language-markdown", "language-html"):
            self.field = attrs["class"].removeprefix("language-")
            if self.field in self.cases[-1]:
                raise ValueError("duplicate example code block")
            self.cases[-1][self.field] = ""

    def handle_endtag(self, tag):
        if tag == "code":
            self.field = None

    def handle_data(self, data):
        if self.field is not None:
            self.cases[-1][self.field] += data


def generate(path):
    raw = path.read_bytes()
    digest = "b153d814fdfc8624bb6da7449162c1cd707a637f7d1c1b636eb44b9cf63fa220"
    if hashlib.sha256(raw).hexdigest() != digest:
        raise ValueError("input is not the pinned GFM 0.29-gfm specification HTML")
    parser = AutolinksExtension()
    parser.feed(raw.decode("utf-8"))
    parser.close()
    if [case["number"] for case in parser.cases] != list(range(622, 636)):
        raise ValueError("AutolinksExtension section membership changed")
    lines = [
        "// Generated by scripts/generate_gfm_autolinks_extension.py; do not edit by hand.",
        "// GFM 0.29-gfm (2019-04-06), complete Autolinks (extension) section.",
        "// GitHub; based on the CommonMark specification by John MacFarlane.",
        "// Source: https://github.github.com/gfm/#autolinks-extension-",
        "// License: CC BY-SA 4.0 https://creativecommons.org/licenses/by-sa/4.0/",
        f"// Full specification HTML SHA-256: {digest}",
        "// Code-block contents copied verbatim after decoding HTML presentation markup.",
        "const BARE_CASES: &[(usize, &str, &str)] = &[",
    ]
    for case in parser.cases:
        lines.append(f'    // Official HTML line {case["line"]}; #example-{case["number"]}.')
        lines.append(f'    ({case["number"]},')
        for field in ["markdown", "html"]:
            # All pinned examples are ASCII; JSON escaping is Rust-compatible
            # here and preserves invisible spaces without source trailing space.
            if not case[field].isascii():
                raise ValueError("non-ASCII example needs explicit Rust escaping")
            lines.append(f'        {json.dumps(case[field])},')
        lines.append("    ),")
    lines.append("];")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("spec", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate(args.spec)
    if args.check:
        fixture = Path(__file__).resolve().parents[1] / "crates/mdstream-core/tests/fixtures/gfm_autolinks_extension.rs"
        if fixture.read_text() != generated:
            parser.error("checked-in AutolinksExtension fixture differs from the pinned upstream data")
        print("GFM 0.29-gfm AutolinksExtension fixture: 14 verbatim examples verified")
    else:
        print(generated, end="")


if __name__ == "__main__":
    main()
