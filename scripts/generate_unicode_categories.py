#!/usr/bin/env python3
"""Generate fixed Unicode 17.0.0 emphasis classes; --check verifies offline."""

import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data/unicode/17.0.0/DerivedGeneralCategory.txt"
OUTPUT = ROOT / "crates/mdstream-core/src/unicode_categories.rs"
DATA_SHA256 = "d62e5bab70ca74f099343f71224fa051cb1fdd61a1ab45c0488c44cfc0b6102e"
LICENSE_SHA256 = "e7a93b009565cfce55919a381437ac4db883e9da2126fa28b91d12732bc53d96"


def generate(source):
    raw = source.read_bytes()
    if hashlib.sha256(raw).hexdigest() != DATA_SHA256:
        raise ValueError("input is not pinned Unicode 17.0.0 DerivedGeneralCategory.txt")
    if hashlib.sha256((ROOT / "data/unicode/LICENSE.txt").read_bytes()).hexdigest() != LICENSE_SHA256:
        raise ValueError("Unicode License V3 differs from the pinned copy")
    ranges = []
    for line in raw.decode("utf-8").splitlines():
        body = line.split("#", 1)[0].strip()
        if not body:
            continue
        codes, category = map(str.strip, body.split(";"))
        if category != "Zs" and category[0] not in "PS":
            continue
        ends = [int(c, 16) for c in codes.split("..")]
        start, end = max(128, ends[0]), ends[-1]
        if start > end:
            continue
        assert end <= 0x10FFFF and not (start <= 0xDFFF and end >= 0xD800)
        ranges.append((start, end, "White" if category == "Zs" else "Punct"))
    merged = []
    for start, end, kind in sorted(ranges):
        assert not merged or merged[-1][1] < start
        if merged and merged[-1][1] + 1 == start and merged[-1][2] == kind:
            merged[-1] = (merged[-1][0], end, kind)
        else:
            merged.append((start, end, kind))
    assert len(merged) < 1024  # <= 11 comparisons in Rust binary_search_by.
    lines = [
        "// Generated by scripts/generate_unicode_categories.py; do not edit.",
        "// Unicode 17.0.0 non-ASCII Zs (White), P/S (Punct); others are Other.",
        "// Source: https://www.unicode.org/Public/17.0.0/ucd/extracted/DerivedGeneralCategory.txt",
        f"// Input SHA-256: {DATA_SHA256}",
        "// Unicode License V3: data/unicode/LICENSE.txt (copyright/permission notice).",
        f"// {len(merged)} sorted, disjoint ranges. ASCII is classified separately.",
        "use super::Class;",
        "",
        "pub(super) static RANGES: &[(char, char, Class)] = &[",
    ]
    for start, end, kind in merged:
        lines.append(f"    ('\\u{{{start:x}}}', '\\u{{{end:x}}}', Class::{kind}),")
    lines.append("];")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", nargs="?", type=Path, default=SOURCE)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = generate(args.source)
    if args.check:
        if OUTPUT.read_bytes() != result.encode("utf-8"):
            parser.error("checked-in emphasis classes differ from pinned Unicode data")
        print("Unicode 17.0.0: data/license hashes, disjoint Zs/P/S ranges and comparison bound verified")
    else:
        print(result, end="")


if __name__ == "__main__":
    main()
