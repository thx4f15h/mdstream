#!/usr/bin/env python3
"""Audit pinned source membership AND execute every chapter's scoring report.

Run inside nix develop with local CommonMark spec.json and GFM HTML paths.
The existing generators remain the verbatim-fixture authority. This tool uses
nextest's freshly built binary/test inventory, then runs each exact report with
libtest to collect its per-example classifications. No parser is reimplemented.
--output writes a reviewable Markdown snapshot; counts are never acceptance
thresholds. A changed classification is governed by the chapter test itself.
"""

import argparse
from collections import Counter
import hashlib
from html.parser import HTMLParser
import importlib.util
import json
from pathlib import Path
import re
import subprocess
import sys

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[1]
TESTS = ROOT / "crates/mdstream-core/tests"
CM_SHA = "d431b29d97b6f73e69d547109cf5081578fac931e72afe95639ebe766c1b2a20"
GFM_SHA = "b153d814fdfc8624bb6da7449162c1cd707a637f7d1c1b636eb44b9cf63fa220"
GFM_SECTIONS = {"tables-extension-", "task-list-items-extension-",
                "strikethrough-extension-", "autolinks-extension-"}


class Sections(HTMLParser):
    """Index official GFM headings/IDs independently of the fixture extractors."""
    def __init__(self):
        super().__init__()
        self.section = None
        self.examples = {}

    def handle_starttag(self, tag, attributes):
        attrs = dict(attributes)
        if tag in ("h1", "h2"):
            self.section = attrs.get("id")
        if tag == "div" and attrs.get("class") == "example":
            number = int(attrs["id"].removeprefix("example-"))
            if number in self.examples:
                raise ValueError(f"duplicate official GFM example {number}")
            self.examples[number] = self.section


def require(condition, message):
    if not condition:
        raise ValueError(message)


def ranges(numbers):
    groups = []
    for n in sorted(numbers):
        if groups and n == groups[-1][-1] + 1:
            groups[-1].append(n)
        else:
            groups.append([n])
    return ", ".join(str(g[0]) if len(g) == 1 else f"{g[0]}–{g[-1]}" for g in groups) or "—"


def audit(args):
    for path, digest in [(args.commonmark, CM_SHA), (args.gfm, GFM_SHA)]:
        require(hashlib.sha256(path.read_bytes()).hexdigest() == digest,
                f"source SHA-256 mismatch: {path}")
    cm = {c["example"]: c["section"] for c in json.loads(args.commonmark.read_bytes())}
    require(set(cm) == set(range(1, 653)), "CommonMark source membership changed")
    gfm = Sections()
    gfm.feed(args.gfm.read_text())
    gfm.close()
    sections = {"commonmark": cm, "gfm": gfm.examples}
    excluded = {n for n, section in cm.items() if section in {"HTML blocks", "Raw HTML"}}
    wanted = {"commonmark": set(cm) - excluded,
              "gfm": {n for n, section in gfm.examples.items() if section in GFM_SECTIONS}}
    suites = []
    for test in sorted(TESTS.glob("*.rs")):
        family = test.stem.split("_")[0]
        if family not in sections:
            continue
        source = test.read_text()
        fixtures = re.findall(r'include!\("fixtures/([^"/]+)"\);', source)
        reports = re.findall(r'#\[test\]\s+fn (pinned_\w+_report)\(\)', source)
        require(len(fixtures) == len(reports) == 1, f"ambiguous score binding: {test}")
        fixture = TESTS / "fixtures" / fixtures[0]
        stored = fixture.read_text()
        generator = re.search(r"Generated by (scripts/\w+\.py);", stored)
        require(generator, f"missing generator: {fixture}")
        script = ROOT / generator[1]
        module_spec = importlib.util.spec_from_file_location(script.stem, script)
        module = importlib.util.module_from_spec(module_spec)
        module_spec.loader.exec_module(module)
        spec = args.commonmark if family == "commonmark" else args.gfm
        require(module.generate(spec) == stored, f"fixture differs from generator: {fixture}")
        ids = [int(n) for n in re.findall(r"^    \((\d+),$", stored, re.M)]
        require(ids and len(ids) == len(set(ids)), f"empty/duplicate fixture: {fixture}")
        require(set(ids) <= wanted[family], f"out-of-scope/unknown IDs: {fixture}")
        chapter = {sections[family][n] for n in ids}
        require(len(chapter) == 1, f"mixed source chapters: {fixture}")
        suites.append((test.stem, family, chapter.pop(), reports[0], ids, generator[1]))
    for family in wanted:
        members = Counter(n for _, f, _, _, ids, _ in suites if f == family for n in ids)
        require(set(members) == wanted[family] and set(members.values()) == {1},
                f"{family}: missing {ranges(wanted[family] - members.keys())}; "
                f"duplicate {ranges(n for n, count in members.items() if count != 1)}")
    if args.sources_only:
        print(f"Sources/generators/unique members verified: {len(wanted['commonmark'])} CommonMark, "
              f"{len(wanted['gfm'])} GFM. Scoring tests NOT executed.")
        return
    # nextest builds from this workspace/toolchain. Never trust an old target
    # directory, a Rust source filename, an ignored test, or a cached report.
    listing = subprocess.run(["cargo", "nextest", "list", "--message-format", "json"],
                             cwd=ROOT, check=True, stdout=subprocess.PIPE, text=True)
    binaries = {s["binary-name"]: s for s in json.loads(listing.stdout)["rust-suites"].values()
                if s["kind"] == "test"}
    lines = ["# Standard syntax scoring coverage", "",
             "Generated by `scripts/check_syntax_coverage.py` from pinned sources and successful exact scoring tests.",
             "This is a classification snapshot, not a claim of CommonMark/GFM compatibility. Chapter tests own classifications; reruns compute them afresh.", "",
             f"CommonMark 0.31.2 spec.json SHA-256: `{CM_SHA}`.",
             f"GFM 0.29-gfm (2019-04-06) full HTML SHA-256: `{GFM_SHA}`.", "",
             "Every in-scope ID occurs exactly once below. Each row binds `tests/<suite>.rs`, its included `tests/fixtures/<suite>.rs`, the generator shown, and the exact report test.",
             "The `commonmark_autolinks_official` suite includes `commonmark_autolinks_official.rs`; older selected `commonmark_autolinks.rs`/`commonmark_display.rs` fixtures are additional overlapping tests, not extra chapter coverage.", "",
             "| Suite / official chapter | IDs | Exact executable report | Generator | Supported IDs | Deliberate difference IDs | Unsupported IDs |",
             "| --- | --- | --- | --- | --- | --- | --- |"]
    totals = {family: [0, 0, 0] for family in wanted}
    for name, family, chapter, report, ids, generator in suites:
        suite = binaries[name]
        require(report in suite["testcases"] and not suite["testcases"][report]["ignored"],
                f"missing/ignored executable scoring test: {name}::{report}")
        result = subprocess.run([suite["binary-path"], "--exact", report, "--nocapture"],
                                cwd=suite["cwd"], check=True, capture_output=True, text=True)
        output = result.stdout + result.stderr
        require("1 passed; 0 failed; 0 ignored" in output, f"report did not run: {name}")
        categories = [[], [], []]
        for number, label in re.findall(r"^example (\d+): (supported|deliberate difference|unsupported|category [012])\b", output, re.M):
            category = int(label[-1]) if label.startswith("category") else ["supported", "deliberate difference", "unsupported"].index(label)
            categories[category].append(int(number))
        emitted = [n for group in categories for n in group]
        require(Counter(emitted) == Counter(ids), f"executed report omitted/duplicated fixture IDs: {name}")
        totals[family] = [a + len(b) for a, b in zip(totals[family], categories)]
        lines.append(f"| `{name}` / {chapter} | {ranges(ids)} | `{report}` | `{generator}` | "
                     + " | ".join(ranges(group) for group in categories) + " |")
    lines += ["", "Explicit chapter exclusions (no silent omissions):", ""]
    for chapter in ["HTML blocks", "Raw HTML"]:
        lines.append(f"- CommonMark {chapter}: {ranges(n for n, s in cm.items() if s == chapter)}; HTML is outside requirements.")
    lines.append("- GFM Disallowed Raw HTML / tagfilter: "
                 + ranges(n for n, s in gfm.examples.items() if s == "disallowed-raw-html-extension-")
                 + "; HTML filtering is outside requirements. GFM base chapters are not a second CommonMark version audit.")
    lines += ["", "Examples containing HTML within included non-HTML chapters remain scored as Unsupported where appropriate; only the two complete CommonMark HTML chapters are excluded.",
              "Unsupported and deliberate differences retain exact chapter observations/rejection checks and the remaining implementation TODOs. Coverage does not convert either category to Supported.", ""]
    for family, counts in totals.items():
        lines.append(f"{family}: {sum(counts)} executed examples; {counts[0]} supported, {counts[1]} deliberate differences, {counts[2]} unsupported.")
    rendered = "\n".join(lines) + "\n"
    if args.output:
        args.output.write_text(rendered)
        print(f"Verified {len(suites)} executable reports; snapshot: {args.output}")
    else:
        print(rendered, end="")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("commonmark", type=Path)
    parser.add_argument("gfm", type=Path)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--sources-only", action="store_true")
    args = parser.parse_args()
    try:
        audit(args)
    except (ValueError, KeyError, subprocess.CalledProcessError) as error:
        parser.exit(1, f"coverage audit failed: {error}\n")


if __name__ == "__main__":
    main()
